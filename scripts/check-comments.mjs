#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { parse } from "@babel/parser";

const directives = [
  /^ biome-ignore /,
  /^\/ <reference types="[^"]+" \/>$/,
  /^\* @type \{import\('[^']+'\)\.\w+\} $/,
  /^ Generated by tooling\/caller-voice\/generate\.py\. Do not edit by hand\.$/,
  /^ (@generated|@end) expo-cli|^ The following patterns were generated by expo-cli$/,
  /^ v\d+\.\d+\.\d+$/,
];

const babelPlugins = (path) => {
  if (path.endsWith(".d.ts")) return [["typescript", { dts: true }]];
  if (/\.[cm]?ts$/.test(path)) return ["typescript"];
  if (path.endsWith(".tsx")) return ["typescript", "jsx"];
  return ["jsx"];
};

const lineOf = (source, index) => source.slice(0, index).split("\n").length;

function scriptComments(path, source) {
  const { comments } = parse(source, { sourceType: "unambiguous", plugins: babelPlugins(path) });
  return comments.map((c) => ({ line: c.loc.start.line, text: c.value }));
}

function hashComments(source) {
  return source.split("\n").flatMap((line, i) => {
    const match = /(?:^|\s)#(?!!)(.*)$/.exec(line);
    return match ? [{ line: i + 1, text: match[1] }] : [];
  });
}

function blockComments(source) {
  return [...source.matchAll(/\/\*([\s\S]*?)\*\/|<!--([\s\S]*?)-->/g)].map((m) => ({
    line: lineOf(source, m.index),
    text: m[1] ?? m[2],
  }));
}

function scannerFor(path) {
  if (/\.(?:[cm]?[jt]sx?|cts)$/.test(path)) return (source) => scriptComments(path, source);
  if (/\.(?:ya?ml|sh|py|toml)$|(?:^|\/)(?:\.gitignore|Gemfile)$/.test(path)) return hashComments;
  if (/\.(?:css|html)$/.test(path)) return blockComments;
  return null;
}

const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], { encoding: "utf8" })
  .split("\n")
  .filter(Boolean);

const found = files.flatMap((path) => {
  const scan = scannerFor(path);
  if (!scan || !existsSync(path)) return [];
  return scan(readFileSync(path, "utf8"))
    .filter(({ text }) => !directives.some((d) => d.test(text)))
    .map(({ line, text }) => `${path}:${line}  ${text.trim().split("\n")[0]}`);
});

if (found.length > 0) {
  console.error(found.join("\n"));
  console.error(`
Comments are not allowed in this repo, found ${found.length}.
A comment means the code doesn't explain itself, or it is explaining a workaround.
Don't reword or move it. Fix the code now: name things so they read on their own,
and fix the underlying problem properly instead of working around it.`);
  process.exit(1);
}
