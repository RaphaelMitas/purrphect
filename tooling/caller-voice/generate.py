"""Render the dart app's score caller clips with Qwen3-TTS in one cloned London voice.

uv run generate.py   (Apple Silicon; downloads ~8 GB of model weights on first run)

refs/ are Qwen3-TTS VoiceDesign takes: voice.wav is the voice, lift.wav the 100+ delivery,
and 180.wav a take with "one" and "eighty" stretched by hand, shipped as is.
"""

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import mlx_whisper
import numpy as np
import soundfile as sf
import torch
from qwen_tts import Qwen3TTSModel

HERE = Path(__file__).parent
REFS = HERE / "refs"
APP = HERE.parent.parent / "apps" / "dart"
OUT = APP / "assets" / "sounds" / "caller"
CLIPS_TS = APP / "src" / "lib" / "callerClips.ts"

ONES = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split()
TENS = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
DARTS = {0, 25, 50, *range(1, 21), *range(2, 41, 2), *range(3, 61, 3)}
SCORES = sorted({a + b + c for a in DARTS for b in DARTS for c in DARTS} - {0})
PHRASES = {"noScore": "No score."}


def words(n: int) -> str:
    if n < 20:
        return ONES[n]
    tens, ones = divmod(n, 10)
    return TENS[tens] + (f"-{ONES[ones]}" if ones else "")


def script(n: int) -> str:
    if n < 100:
        return words(n).capitalize() + "."
    if n == 100:
        return "One HUNDRED!"
    # the caller runs "one-hundred-and" together and leans on the final word
    head, _, last = words(n - 100).rpartition("-")
    return f"One-hundred-and-{head + '-' if head else ''}{last.upper()}!"


def norm(text: str) -> str:
    return " ".join(re.sub(r"[^a-z0-9]+", " ", text.lower()).split())


def heard_ok(key: str, heard: str) -> bool:
    if key in PHRASES:
        return norm(heard) == norm(PHRASES[key])
    spoken = norm(script(int(key)))
    return norm(heard) in {key, spoken, spoken.replace(" and ", " ")}


def longest_pause(audio: np.ndarray, sr: int) -> float:
    frame = sr // 100
    db = 20 * np.log10(np.sqrt(np.mean(audio[: len(audio) // frame * frame].reshape(-1, frame) ** 2, axis=1)) + 1e-9)
    loud = np.where(db > db.max() - 35)[0]
    longest = run = 0
    for quiet in db[loud[0] : loud[-1]] < db.max() - 35:
        run = run + 1 if quiet else 0
        longest = max(longest, run)
    return longest / 100


def encode(src: Path, dst: Path):
    partial = dst.with_suffix(".part.mp3")
    trim = "silenceremove=start_periods=1:start_threshold=-45dB"
    chain = f"{trim},areverse,{trim},afade=t=in:d=0.04,areverse,afade=t=in:d=0.005,dynaudnorm=p=0.9:m=8,volume=-1dB"
    try:
        subprocess.run(
            ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(src), "-af", chain,
             "-ar", "24000", "-ac", "1", "-b:a", "48k", str(partial)],
            check=True,
        )
        partial.replace(dst)
    finally:
        partial.unlink(missing_ok=True)


def write_clips_ts(keys: list[str]):
    names = {k: f"call{k[0].upper()}{k[1:]}" for k in keys}
    imports = "\n".join(f'import {names[k]} from "../../assets/sounds/caller/{k}.mp3";' for k in keys)
    entries = "\n".join(f"  {k}: {names[k]}," for k in keys)
    CLIPS_TS.write_text(
        "// Generated by tooling/caller-voice/generate.py. Do not edit by hand.\n"
        'import type { Call } from "@/game/call";\n'
        f"{imports}\n\n"
        f"export const CALL_CLIPS: Readonly<Partial<Record<Call, number>>> = {{\n{entries}\n}};\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--attempts", type=int, default=6)
    parser.add_argument("--device", default="mps")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    model = Qwen3TTSModel.from_pretrained(
        "Qwen/Qwen3-TTS-12Hz-1.7B-Base", device_map=args.device, dtype=torch.bfloat16, attn_implementation="sdpa"
    )
    calm = model.create_voice_clone_prompt(ref_audio=str(REFS / "voice.wav"), x_vector_only_mode=True)
    lift = model.create_voice_clone_prompt(ref_audio=str(REFS / "lift.wav"), ref_text="One hundred and forty!")

    lines = {str(n): (script(n), calm if n < 100 else lift) for n in SCORES if n != 180}
    lines |= {key: (text, calm) for key, text in PHRASES.items()}

    failed = []
    for i, (key, (text, prompt)) in enumerate(lines.items()):
        dst = OUT / f"{key}.mp3"
        if dst.exists():
            continue
        for attempt in range(args.attempts):
            torch.manual_seed(1000 * attempt + i)
            wavs, sr = model.generate_voice_clone(text=text, language="English", voice_clone_prompt=prompt)
            audio = wavs[0]
            with tempfile.NamedTemporaryFile(suffix=".wav") as tmp:
                sf.write(tmp.name, audio, sr)
                heard = mlx_whisper.transcribe(tmp.name, path_or_hf_repo="mlx-community/whisper-large-v3-turbo", language="en")["text"]
                if heard_ok(key, heard) and longest_pause(audio, sr) <= 0.2 and len(audio) / sr < 5:
                    encode(Path(tmp.name), dst)
                    print(f"{key}: {text} -> {heard.strip()} (attempt {attempt + 1})", flush=True)
                    break
        else:
            failed.append(key)
            print(f"{key}: FAILED after {args.attempts} attempts, last heard {heard.strip()!r}", flush=True)

    if failed:
        sys.exit(f"Re-run with more --attempts to retry: {', '.join(failed)}")
    encode(REFS / "180.wav", OUT / "180.mp3")
    write_clips_ts([str(n) for n in SCORES] + sorted(PHRASES))


if __name__ == "__main__":
    main()
